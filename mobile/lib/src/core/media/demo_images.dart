    'debate': clubDebate,
    'entrepreneurship': innovationNight,
    'wellness': eventSocial,
    'housing': housingRoom,
    'marketplace': marketDesk,
  };

  static CampusMedia? forCategory(String? category) {
    final key = (category ?? '').trim().toLowerCase();
    if (key.isEmpty) return null;
    final exact = byCategory[key];
    if (exact != null) return exact;
    for (final entry in byCategory.entries) {
      if (key.contains(entry.key)) return entry.value;
    }
    return null;
  }
